let currentLang = "en";
const langToggle = document.getElementById("langToggle");

function applyLanguage(lang) {
  currentLang = lang;
  document.documentElement.lang = lang === "en" ? "en" : "id";
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    if (translations[lang][key]) el.textContent = translations[lang][key];
  });
  document.querySelector(".lang-active").textContent = lang.toUpperCase();
  document.querySelector(".lang-toggle").setAttribute(
    "aria-label",
    lang === "en" ? "Switch to Indonesian" : "Switch to English"
  );
}

langToggle.addEventListener("click", () => applyLanguage(currentLang === "en" ? "id" : "en"));

const menuToggle = document.querySelector(".menu-toggle");
const siteNav = document.querySelector(".site-nav");
menuToggle.addEventListener("click", () => {
  const open = siteNav.classList.toggle("open");
  menuToggle.setAttribute("aria-expanded", String(open));
});
document.querySelectorAll(".site-nav a").forEach(link => {
  link.addEventListener("click", () => {
    siteNav.classList.remove("open");
    menuToggle.setAttribute("aria-expanded", "false");
  });
});

document.querySelectorAll(".filter-btn").forEach(btn => {
  btn.addEventListener("click", () => {
    const filter = btn.dataset.filter;
    document.querySelectorAll(".filter-btn").forEach(b => {
      b.classList.remove("active");
      b.setAttribute("aria-selected", "false");
    });
    btn.classList.add("active");
    btn.setAttribute("aria-selected", "true");

    document.querySelectorAll(".project-card").forEach(card => {
      card.classList.toggle("is-hidden", filter !== "all" && card.dataset.category !== filter);
    });
  });
});

const dialog = document.getElementById("projectDialog");
const dialogTitle = document.getElementById("dialogTitle");
const dialogText = document.getElementById("dialogText");
const dialogTags = document.getElementById("dialogTags");
const dialogExtra = document.getElementById("dialogExtra");

document.querySelectorAll(".project-detail").forEach(btn => {
  btn.addEventListener("click", () => {
    const info = projectInfo[btn.dataset.project];
    dialogTitle.textContent = info.title;
    dialogText.textContent = info.text;
    dialogExtra.textContent = info.extra;
    dialogTags.innerHTML = info.tags.map(tag => `<span>${tag}</span>`).join("");
    dialog.showModal();
  });
});
document.querySelector(".dialog-close").addEventListener("click", () => dialog.close());
dialog.addEventListener("click", e => {
  if (e.target === dialog) dialog.close();
});

